#!/usr/bin/env python3
"""updater/locale/locale.json -> updater/src/update_words.inc (the updater's words, compiled into the Native Core and the Slots Loader's
plugin). Run after any change of that file; check_locale.py fails when the generated file is not up to date."""
import json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from gen_plugin_words import LANGS, cstr, ident  # noqa: E402

REPO = os.path.dirname(os.path.dirname(HERE))
LOCALE = os.path.join(REPO, "updater", "locale", "locale.json")
OUT = os.path.join(REPO, "updater", "src", "update_words.inc")


def generate():
    loc = json.load(open(LOCALE, encoding="utf-8"))
    keys = list(loc["en"].keys())
    o = ["// Generated by tools/localisation/gen_updater_words.py from updater/locale/locale.json: do not edit.", ""]
    o.append("enum class Word : int {")
    o += ["    %s,   // %s" % (ident(k[len("update."):] if k.startswith("update.") else k), k) for k in keys]
    o += ["    Count", "};", ""]
    o.append("inline constexpr int kLangCount = %d;" % len(LANGS))
    o.append("inline constexpr const char* kLangs[kLangCount] = { %s };" % ", ".join(cstr(l) for l in LANGS))
    o.append("inline constexpr const char* kText[kLangCount][static_cast<int>(Word::Count)] = {")
    for lang in LANGS:
        o.append("    {   // %s" % lang)
        tbl = loc.get(lang, {})
        o += ["        %s," % (cstr(tbl[k]) if tbl.get(k) else "nullptr") for k in keys]
        o.append("    },")
    o += ["};", ""]
    return "\n".join(o)


def main():
    text = generate()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("update_words.inc is not up to date: run tools/localisation/gen_updater_words.py")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("written", OUT)


if __name__ == "__main__":
    main()
