#!/usr/bin/env python3
"""tools/sorter/locale.json -> tools/sorter/texts_table.inc: SF6_ModSorter's texts as a C++ table (the tool is one exe: its
texts are compiled in). Run after every edit of the table; --check tells whether the generated file is up to date.

The table's keys are the tool's TextId names, in the order of the English block. A text missing in a language is written as
an empty string: the tool then shows the English one."""
import os
import re
import sys

from locale_common import LANGS, REPO, read_table

TABLE = os.path.join(REPO, "tools", "sorter", "locale.json")
OUT = os.path.join(REPO, "tools", "sorter", "texts_table.inc")
# The Windows locale of each language: DirectWrite's font choice (which Han shapes), capitals
LOCALES = {"en": "en-us", "fr": "fr-fr", "ja": "ja-jp", "zh-Hans": "zh-cn", "it": "it-it", "de": "de-de", "es": "es-es",
           "es-419": "es-mx", "ru": "ru-ru", "pl": "pl-pl", "pt": "pt-br", "ko": "ko-kr", "zh-Hant": "zh-tw", "ar": "ar-sa"}
# Each language's name in the language itself: the values of the Options page's Language row (never translated)
NAMES = {"en": "English", "fr": "Français", "ja": "日本語", "zh-Hans": "简体中文", "it": "Italiano", "de": "Deutsch", "es": "Español",
         "es-419": "Español (Latinoamérica)", "ru": "Русский", "pl": "Polski", "pt": "Português (Brasil)", "ko": "한국어",
         "zh-Hant": "繁體中文", "ar": "العربية"}
ARG = re.compile(r"\{\d\}")


def args_of(text):
    return sorted(set(ARG.findall(text)))


def c_string(text):
    """A C string literal of the text's UTF-8 bytes: octal escapes (three digits, so a digit after one is never taken in)."""
    out = []
    for b in text.encode("utf-8"):
        if b in (0x22, 0x5C):
            out.append("\\" + chr(b))
        elif 0x20 <= b < 0x7F and b != 0x3F:      # '?' escaped too: no trigraph
            out.append(chr(b))
        else:
            out.append("\\%03o" % b)
    return '"' + "".join(out) + '"'


def generate():
    table = read_table(TABLE)
    keys = list(table["en"])
    lines = ["// Generated by tools/localisation/gen_sorter_texts.py from tools/sorter/locale.json: do not edit.",
             "// The texts are UTF-8, written as octal escapes.", "",
             "enum TextId {"]
    for i in range(0, len(keys), 6):
        lines.append("    " + ", ".join(keys[i:i + 6]) + ",")
    lines += ["    T__COUNT", "};", "",
              "inline constexpr int kLangCount = %d;" % len(LANGS),
              "inline const char* const kLangCodes[kLangCount] = { %s };" % ", ".join('"%s"' % c for c in LANGS),
              "inline const wchar_t* const kLangLocales[kLangCount] = { %s };" % ", ".join('L"%s"' % LOCALES[c] for c in LANGS),
              "inline const char* const kLangNames[kLangCount] = { %s };" % ", ".join(c_string(NAMES[c]) for c in LANGS),
              "", "inline const char* const kTextTable[kLangCount][T__COUNT] = {"]
    for lang in LANGS:
        block = table.get(lang, {})
        lines.append("    {   // " + lang)
        for k in keys:
            lines.append("        /* %s */ %s," % (k, c_string(block.get(k, ""))))
        lines.append("    },")
    lines += ["};", ""]
    return "\n".join(lines)


def checks():
    """What must hold in the table: (ok, what) pairs."""
    table = read_table(TABLE)
    en = table["en"]
    out = []
    ctx = table.get("_context", {})
    for k in en:
        out.append((re.fullmatch(r"[A-Z][A-Z0-9_]*", k) is not None, "Mod Sorter: %s: not a C++ name" % k))
        out.append((bool(ctx.get(k, {}).get("where")), "Mod Sorter: %s: no _context where" % k))
    for k in ctx:
        out.append((k in en, "Mod Sorter: _context has %s, the English block has not" % k))
    for lang in LANGS:
        block = table.get(lang)
        out.append((block is not None, "Mod Sorter: no [%s] block" % lang))
        if block is None:
            continue
        for k in block:
            out.append((k in en, "Mod Sorter: %s [%s]: not in the English block" % (k, lang)))
        for k, source_text in en.items():
            text = block.get(k, "")
            out.append((bool(text.strip()), "Mod Sorter: %s [%s]: missing" % (k, lang)))
            if text:
                out.append((args_of(text) == args_of(source_text),
                            "Mod Sorter: %s [%s]: arguments %s, English %s" % (k, lang, args_of(text), args_of(source_text))))
                out.append(("\n" not in text and text == text.strip(), "Mod Sorter: %s [%s]: a line break or a space at an end" % (k, lang)))
    # every key is used by the tool, every TextId the tool uses is a key
    used = set()
    src_dir = os.path.join(REPO, "tools", "sorter")
    for name in os.listdir(src_dir):
        if name.endswith((".cpp", ".hpp")):
            with open(os.path.join(src_dir, name), encoding="utf-8") as f:
                used |= set(re.findall(r"\b[TRED]_[A-Z0-9_]+\b", f.read()))
    used.discard("T__COUNT")
    for k in en:
        out.append((k in used, "Mod Sorter: %s is in the table, the tool does not use it" % k))
    for k in sorted(used - set(en)):
        out.append((False, "Mod Sorter: the tool uses %s, the table has not" % k))
    try:
        with open(OUT, encoding="utf-8", newline="") as f:
            current = f.read().replace("\r\n", "\n")
    except OSError:
        current = None
    out.append((current == generate(), "Mod Sorter: tools/sorter/texts_table.inc is not up to date (run gen_sorter_texts.py)"))
    return out


def main():
    if "--check" in sys.argv[1:]:
        bad = [what for ok, what in checks() if not ok]
        for what in bad:
            print("FAIL " + what)
        print("%d checks, %d failed" % (len(checks()), len(bad)))
        return 1 if bad else 0
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(generate())
    print("wrote %s" % os.path.relpath(OUT, REPO))
    return 0


if __name__ == "__main__":
    sys.exit(main())
