#!/usr/bin/env python3
"""plugin/locale/locale.json + game_words.json -> plugin/src/words_table.inc (the Slots Loader's words, compiled in).
Run after any change of those two files; check_locale.py fails when the generated file is not up to date."""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
LOCALE = os.path.join(REPO, "plugin", "locale", "locale.json")
GAME = os.path.join(REPO, "plugin", "locale", "game_words.json")
OUT = os.path.join(REPO, "plugin", "src", "words_table.inc")
LANGS = ["en", "fr", "ja", "zh-Hans", "it", "de", "es", "es-419", "ru", "pl", "pt", "ko", "zh-Hant", "ar"]


def cstr(s):
    """A C string, ASCII only: the build has no source encoding of its own. Octal escapes: they never eat the next character."""
    out = []
    octal = False
    for b in s.encode("utf-8"):
        c = chr(b)
        if c == '"' or c == "\\":
            out.append("\\" + c)
            octal = False
        elif c == "\n":
            out.append("\\n")
            octal = False
        elif 0x20 <= b < 0x7F and c != "?" and not (octal and c.isdigit()):   # a digit after an octal escape: compilers warn
            out.append(c)
            octal = False
        else:
            out.append("\\%03o" % b)
            octal = True
    return '"' + "".join(out) + '"'


def ident(key):
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[._-]", key))


def generate():
    loc = json.load(open(LOCALE, encoding="utf-8"))
    game = json.load(open(GAME, encoding="utf-8"))
    keys = list(loc["en"].keys())
    o = ["// Generated by tools/localisation/gen_plugin_words.py from plugin/locale/: do not edit.", ""]
    o.append("enum class W : int {")
    o += ["    %s,   // %s" % (ident(k), k) for k in keys]
    o += ["    Count", "};", ""]
    o.append("enum class G : int {")
    o += ["    %s,   // %s" % (ident(w["key"]), w["key"]) for w in game["words"]]
    o += ["    Count", "};", ""]
    o.append("inline constexpr int kLangCount = %d;" % len(LANGS))
    o.append("inline constexpr const char* kLangs[kLangCount] = { %s };" % ", ".join(cstr(l) for l in LANGS))
    o.append("inline constexpr const char* kWordKeys[] = {")
    o += ["    %s," % cstr(k) for k in keys]
    o += ["};", ""]
    o.append("inline constexpr const char* kText[kLangCount][static_cast<int>(W::Count)] = {")
    for lang in LANGS:
        o.append("    {   // %s" % lang)
        tbl = loc.get(lang, {})
        o += ["        %s," % (cstr(tbl[k]) if tbl.get(k) else "nullptr") for k in keys]
        o.append("    },")
    o += ["};", ""]
    o.append("inline constexpr GameWordRow kGameWords[] = {")
    o += ["    { %s, %s, %s }," % (cstr(w["key"]), cstr(w["guid"]), cstr(w["english"])) for w in game["words"]]
    o += ["};", ""]
    o.append("inline constexpr FighterRow kFighterWords[] = {")
    o += ["    { %d, %s, %s, %s }," % (f["fid"], cstr(f["english"]), cstr(f["name_guid"]), cstr(f["caption_guid"])) for f in game["fighters"]]
    o += ["};", ""]
    return "\n".join(o)


def main():
    text = generate()
    if "--check" in sys.argv:
        cur = open(OUT, encoding="utf-8", newline="").read().replace("\r\n", "\n") if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("words_table.inc is not up to date: run tools/localisation/gen_plugin_words.py")
        return
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("written", OUT)


if __name__ == "__main__":
    main()
